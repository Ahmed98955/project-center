def set_rtl(p):
    pPr = p._p.get_or_add_pPr()
    bidi = pPr.makeelement(qn('w:bidi'), {qn('w:val'): '1'})
    pPr.append(bidi)


def add_para(doc, text, size=12, bold=False, color=None, align=None, space_after=6):
    p = doc.add_paragraph()
    set_rtl(p)
    r = p.add_run(text)
    r.font.name = 'Arial'
    r.font.size = Pt(size)
    r.font.bold = bold
    if color:
        r.font.color.rgb = color
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space_after)
    return p


def add_label(doc, text, color=NAVY):
    add_para(doc, text, size=11, bold=True, color=color, space_after=2)


def add_body(doc, text, bold=False, color=None, size=11.5):
    add_para(doc, text, size=size, bold=bold, color=color, space_after=4)


